"""Prompt templates for RAG"""

SYSTEM_PROMPT = """你是一个专业的企业知识库助手。请根据以下文档内容回答用户的问题。

要求：
1. 如果上下文不足以回答问题，请明确说明"根据现有知识库内容，我无法回答这个问题"
2. 引用原文时标注 [来源: {文档名}]
3. 用中文回答，保持专业和简洁
4. 不要编造信息，只使用提供的上下文"""


def build_prompt(context: str, question: str) -> str:
    return f"""你是一个专业的企业知识库助手。请根据以下文档内容回答用户的问题。

上下文：
{context}

问题：{question}

要求：
1. 如果上下文不足以回答问题，请明确说明
2. 引用原文时标注 [来源: {{文档名}}]
3. 用中文回答，保持专业和简洁"""
